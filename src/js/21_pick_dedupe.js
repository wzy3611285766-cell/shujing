/* ---------- 抽题避重 ----------
   老逻辑只记"上一次抽的那一题"，隔一题就能原样回来 ——
   玩家看到的就是"上一秒才做过，下一秒又是它"。
   现在每个 (域, 档) 各自维护一条最近队列：
     · 窗口取池子的一半，留足回旋余地（池子 9 题就避最近 4 题）
     · 池子小到窗口都放不下时，窗口自动收到 池子−1，保证永远有题可出
   题干是带随机数的（比如 x²−4x 与 x²−6x 是同一模板的不同实例），
   所以用 pool 里的下标做 key，同模板不同参数仍算两道题。 */
const lastPick={};
const SEEN_MAX=8;                       /* 每个池记最近出过几个下标 */
const THINK_MARK={};                    /* rid|tier -> boolean[]：池内哪些是「思路·」元问题 */
function genQuestion(rid,tier,noThink){
  let pool=(BANK[rid]&&BANK[rid][clamp(tier,1,3)])||BANK.func[1];
  /* 闯关 / 烽火要「实题」：跳过 src 以「思路·」开头的元问题（172 版起，
     那是练枪场才练的内容）。池子被跳空时退回全池 —— 宁可偶尔出一题，
     也不能出现抽不出题的空白。分类结果按池缓存，只算一次。 */
  if(noThink){
    const mk=rid+'|'+tier;
    if(!THINK_MARK[mk])THINK_MARK[mk]=pool.map(f=>{
      try{const q=f();return /^思路/.test(String((q&&q.src)||''));}catch(e){return false;}
    });
    const f=pool.filter((_,i)=>!THINK_MARK[mk][i]);
    if(f.length)pool=f;
  }
  if(!pool.length)pool=BANK.func[1];
  if(pool.length<2)return pick(pool)();
  /* 实题池与全池各记各的去重窗口：不然两边的下标口径会互相错位 */
  const key=rid+'|'+tier+(noThink?'|n':'');
  if(!lastPick[key])lastPick[key]=[];
  const seen=lastPick[key];
  /* 窗口别吃满池子：至少留一个能抽 */
  let win=Math.min(SEEN_MAX,Math.max(1,pool.length-1));
  if(seen.length>win)seen.splice(0,seen.length-win);
  /* 先在"最近没出过的"里随机；全被占满（池子太小）才退回全池 */
  const free=[];
  for(let i=0;i<pool.length;i++)if(seen.indexOf(i)<0)free.push(i);
  const i=free.length?pick(free):Math.floor(Math.random()*pool.length);
  seen.push(i);
  return pool[i]();
}

