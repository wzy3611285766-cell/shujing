/* =========================================================
   🧗 母题阶梯（4.0.0）
   ---------------------------------------------------------
   学生最怕"创新题"。但创新题不是凭空冒出来的 —— 它是把课本模型
   一层层包起来。不会做的真正原因是【跳级】：一上来就做包装了三层的题，
   中间缺台阶。所以每个核心模型做成三级：
     lv0 母题　　：课本原型，条件砍到最干净，先把方法本身练熟
     lv1 变式　　：同一个模型换个皮、加一个条件
     lv2 出其不意：形式陌生，但完全在考纲内 —— 会了前两级就能下手
   三级共用 mid（模型 id），点模型名就按顺序连刷三道，
   照样带 hints / steps / appr，卡住就点提示，不丢人。
   题目本身仍然进 BIG（练枪场照常能随机刷到），阶梯只是多给一条
   "按顺序爬"的路。
   ========================================================= */
const LADDERS={};
const LADDER_ORDER=[];
function QL(o){
  const q=QB(o);
  q.lad=o.mid;
  q.lv=o.lv||0;
  q.model=o.model||'';
  if(!LADDERS[o.mid]){
    LADDERS[o.mid]={id:o.mid,n:o.nm||'模型',s:o.s,rid:o.rid,
      model:o.model||'',ks:[null,null,null]};
    LADDER_ORDER.push(o.mid);
  }
  LADDERS[o.mid].ks[q.lv]=q;
  return q;
}
/* 三级齐了才让进阶梯 —— 缺一级的话爬到一半断掉，比没有还难受 */
function ladderFull(id){
  const L=LADDERS[id];
  return !!(L&&L.ks[0]&&L.ks[1]&&L.ks[2]);
}
function ladderList(sid){
  return LADDER_ORDER.map(id=>LADDERS[id])
    .filter(L=>ladderFull(L.id)&&(!sid||L.s===sid));
}
/* 阶梯进度存在 state.lad：{模型id:{n:做过几题, r:对几题, lv:已过到第几级}} */
function ladStat(id){
  if(!state.lad)state.lad={};
  if(!state.lad[id])state.lad[id]={n:0,r:0,lv:-1};
  return state.lad[id];
}
function ladMark(id){
  const st=ladStat(id);
  if(st.n===0)return '⬜';
  if(st.lv>=2&&st.r/st.n>=0.67)return '🏆';
  return '🟡';
}
/* 开一轮阶梯：三道题按 lv0→lv1→lv2 发牌，不随机、不去重 */
function ladderSession(id){
  const L=LADDERS[id];
  if(!ladderFull(id)){toast('这个模型还没配齐三级，先刷别的');return;}
  /* 题干和选项都要拷一份：答题过程会改 q.opts 之外的状态，
     共用同一个对象会污染下次进来时的起点 */
  const ks=L.ks.map(q=>{
    const c=Object.assign({},q);
    c.opts=q.opts.slice();
    if(q.appr)c.appr={r:q.appr.r,why:q.appr.why,opts:q.appr.opts.slice()};
    return c;
  });
  drillSession(L.s,{tier:ks[0].d||2,queue:ks,lad:id});
}

/* 该科该档有多少道大题 */
function bigCount(sid,tier){
  return BIG.filter(q=>q.subject===sid&&(tier==null||q.d===tier)).length;
}
function bigList(sid,tier){return BIG.filter(q=>q.subject===sid&&(tier==null||q.d===tier));}
/* 抽一道大题：先按档、再按专题；实在没有就返回 null（调用方退回旧题库） */
function bigDraw(sid,tier,rid,tid,recent){
  let pool=BIG.filter(q=>q.subject===sid);
  if(!pool.length)return null;
  let hit=true;
  /* 同档优先；本档没题就放宽到相邻档，保证一定能刷出大题 */
  let b=pool.filter(q=>q.d===tier);
  if(!b.length){
    const near=[1,2,3].sort((x,y)=>Math.abs(x-tier)-Math.abs(y-tier));
    for(let i=0;i<near.length&&!b.length;i++)b=pool.filter(q=>q.d===near[i]);
    hit=false;
  }
  pool=b;
  if(rid)  {const f=pool.filter(q=>q.rid===rid);  if(f.length)pool=f;}
  if(tid&&tid!=='all'&&typeof topicOfSid==='function'){
    const f=pool.filter(q=>topicOfSid(sid,q.topic)===tid);
    if(f.length)pool=f;
  }
  if(!pool.length)return null;
  const fresh=pool.filter(q=>!(recent&&recent.has(q.text)));
  const src=fresh.length?fresh:pool;
  return {q:pick(src),rid:(src[0].rid||'func'),hit:hit};
}

/* 这个专题有没有攻坚题（决定练枪面板里该不该把这块置灰） */
function hardHasTopic(sid,tid){
  if(!tid||tid==='all')return true;
  return HARD.some(q=>q.subject===sid&&q.topic&&
    (typeof topicOfSid==='function'?topicOfSid(sid,q.topic):null)===tid);
}
function hardCountOf(sid){return hardList(sid).length;}
/* 抽一道攻坚题：定了专题就优先在该专题里找，找不到再退回本科随机 */
function hardDraw(sid,tid,recent){
  let pool=hardList(sid);
  let hit=true;
  if(tid&&tid!=='all'&&typeof topicOfSid==='function'){
    const f=pool.filter(q=>topicOfSid(sid,q.topic)===tid);
    if(f.length)pool=f;else hit=false;
  }
  if(!pool.length)return null;
  const fresh=pool.filter(q=>!(recent&&recent.has(q.text)));
  const src=fresh.length?fresh:pool;
  return {q:pick(src),rid:(src[0].rid||'func'),hit:hit};
}

