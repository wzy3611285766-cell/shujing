/* ---------- 题目构造器 ----------
   Q(题干, 正确项, [干扰项], 解析, 知识点, [备用干扰项], 出处)
   选项一律是"展示字符串"——物理答案是 5 m/s，化学是 H₂SO₄，生物是 AaBb，
   直接用字符串出题，比先算数值再反推选项更贴近真实考卷。 */
/* 第 8、9 个参数允许两种写法，靠类型自动识别：
     老题  (..., src, angles数组)
     新题  (..., src, qt字符串, angles数组)
   题库几百道、跨越多次改动，强行统一顺序迟早会漏改某一处，
   让函数自己认类型比改调用点可靠。 */
function Q(text,correct,wrongs,exp,topic,extra,src,a,b){
  let qt='',angles=null;
  if(typeof a==='string'){qt=a;angles=b||null;}
  else if(Array.isArray(a)){angles=a;qt=typeof b==='string'?b:'';}
  else if(typeof b==='string'){qt=b;}
  const ans=String(correct),set=[ans],seen=new Set([ans]);
  const push=w=>{
    w=String(w);
    if(!w||w===ans||seen.has(w)||set.length>=4)return;
    /* 干扰项生成器偶尔吐出 NaN / undefined / Infinity（化学式的数值型干扰项最常见，
       自检 800 次会撞到一次）。这种选项混进题里就成了"答案写着 NaN"，
       宁可少一个干扰项（题会标 short，界面另有处理），也别让它上桌 */
    if(/undefined|NaN|Infinity/.test(w))return;
    seen.add(w);set.push(w);
  };
  shuffle((wrongs||[]).map(String)).forEach(push);
  shuffle((extra||[]).map(String)).forEach(push);
  decoysFor(ans).forEach(push);
  const q={text,ansText:ans,opts:shuffle(set),exp,topic:topic||'',
    src:src||'',short:set.length<4,appr:null,
    angles:angles||null,qt:qt||''};
  /* appr 要拿到 angles 之后才算：思路层优先吃本题的多解层，
     所以不能在对象字面量里直接调 approachFor(topic) */
  q.appr=approachFor(q);
  return q;
}
/* ---------- 题型（qt）----------
   老题库一题一个知识点，刷完只记得"这题选 B"；
   新题库按「思维动作」分类 —— 练的是同一个动作在不同长相的题里怎么使：
     conv 转化：把陌生表述翻译成熟悉的形式（"这句话其实就是说……"）
     loc  定位：先找突破口，问"第一步该动哪儿" / "题眼在哪"
     nc   非常规：不靠算，靠对称、极端、特殊值、量纲、整体代换直接定
     path 多解：一题几条路，问哪条走得通 / 哪条最省力
     pit  防坑：给一个真会犯的错，问它错在哪（反面练思路最有效）
     cond 条件：增减一个条件，结论怎么变 —— 逼人看清每个条件在管什么
     str  结构：看穿结构就能定（比较大小、判断形状、数形结合）
     mig  迁移：这题和哪题是同一类 / 同一个模型换了个皮
   题型徽章由 srcBadge 渲染，八种各一个颜色。 */
/* ---------- 多解层（angles）----------
   一题多解的记录：同一道题的 2~3 条路，各写清「怎么走」和「什么时候该想到它」。
   angles:[{n:'路名',d:'怎么走',sig:'看到什么信号就该选这条'}]
   n 给方法命名（如"对称性""特殊值"），d 写这条路的走法，
   sig 是关键 —— 只讲"还能这么解"没用，要讲清"什么长相的题该走这条路"，
   学生下次碰到新题才调得出来。 */
/* ---------- 思路层挂载 ----------
   给题目附上 appr：正确思路 + 三条错路 + 一句点睛。
   选项凑不满 4 条就返回 null —— 界面检测到没有 appr 会自动退回单步答题，
   不会露出三个选项的半成品。

   173.1 修正：旧版只按 topic 查 APPROACH（知识点级通用套路），
   导致"思路说 A、解析走 B"的误导 —— 同一 topic 下不同题解法可能完全不同。
   现在优先吃**本题专属**的解法信息：
     ① q.angles[0].n  —— 一题多解层的第一条路名，就是这题的入手方式
     ② q.angles[0].d  —— 该路的走法（路名太短时补足）
   都没有时才退回 topic 通用套路。干扰项仍从 topic 的错路里取
   （"错路"本来就是跨题通用的，这点没问题）。
   兼容两种调用：传 topic 字符串（老调用），或传整个题目对象。 */
function approachFor(q){
  const isObj=q&&typeof q==='object';
  const topic=isObj?q.topic:q;
  const A=APPROACH[topic];
  const ag=(isObj&&q.angles&&q.angles[0])||null;
  /* 本题专属的正确入手点 */
  let right='',why='';
  if(ag){
    right=String(ag.n||'').trim();
    /* 路名太短（如"对称性"三个字）时，把走法带上，选项才有信息量；
       仍控制在 24 字内，选项才扫得完 */
    if(ag.d&&right.length<8){
      const d=String(ag.d).replace(/。+$/,'');
      right=(right?right+'：':'')+d;
    }
    why=String(ag.sig||'').trim();
  }
  if(!right&&A&&A.r)right=A.r;
  if(!right)return null;
  if(!why&&A&&A.k)why=A.k;
  /* 干扰项：优先 topic 的错路（通用错路本就不分题），
     没有 topic 就退而用本题多解层里"其他路"当干扰 ——
     同题的其他解法作干扰，比背模板错路更能逼学生分辨"这题该走哪条" */
  const wrongs=(A&&A.w&&A.w.length)?A.w
    :((isObj&&q.angles)?q.angles.slice(1).map(x=>String((x&&x.n)||'')).filter(Boolean):[]);
  const set=[right],seen=new Set([right]);
  wrongs.forEach(v=>{
    v=String(v||'');
    if(!v||seen.has(v)||set.length>=4)return;
    seen.add(v);set.push(v);
  });
  if(set.length<4)return null;
  return {r:right,opts:shuffle(set),why:why};
}

